// Builds the WorkSuite Local AI ONLYOFFICE plugin (asc.ws-ai) into plugin/dist/ (or --out <dir>):
// plugin/src as it is, plus scripts/pcm-worklet.js, the microphone's AudioWorklet (lib/resampler.js in
// front of scripts/pcm-worklet.src.js: a worklet cannot load scripts). Like Sinhala Tools' build, the
// output depends only on the sources: sorted file order, LF endings, and dist/files.sha256 lists every
// file's sha256. It checks the guid, that every toolbar command has its icons (light and dark, 100% to
// 200%) and that every translation file has every string.
import { createHash } from "node:crypto";
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outArg = process.argv.indexOf("--out");
const out = outArg > 0 ? process.argv[outArg + 1] : join(root, "plugin", "dist");
const src = join(root, "plugin", "src");
const posix = (p) => p.split(sep).join("/");

function walk(dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

export const COMMANDS = ["voice", "transcribe", "readAloud", "spelling", "grammar", "punctuation", "improve", "rewrite",
  "simplify", "formal", "professional", "tone", "expand", "shorten", "summarize", "explain", "translate", "detect", "suggestions"];
export const SCALES = ["", "@1.25x", "@1.5x", "@1.75x", "@2x"];

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(src, out, { recursive: true, filter: (p) => !p.endsWith("pcm-worklet.src.js") });

const lf = (f) => readFileSync(f, "utf8").replace(/\r\n/g, "\n");
writeFileSync(join(out, "scripts", "pcm-worklet.js"),
  "/* generated by ai-plugin/scripts/build-plugin.mjs from lib/resampler.js and scripts/pcm-worklet.src.js, do not edit. */\n" +
  lf(join(src, "lib", "resampler.js")) + "\n" + lf(join(src, "scripts", "pcm-worklet.src.js")));

const config = JSON.parse(readFileSync(join(out, "config.json"), "utf8"));
if (!/^asc\.\{[0-9A-F]{8}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{12}\}$/.test(config.guid)) {
  throw new Error("config.json guid must be asc.{GUID}");
}
const missing = [];
for (const theme of ["light", "dark"]) {
  for (const name of ["icon", ...COMMANDS]) {
    for (const s of SCALES) {
      try { statSync(join(out, "resources", theme, name + s + ".png")); } catch { missing.push(`${theme}/${name}${s}.png`); }
    }
  }
}
if (missing.length) throw new Error("icons missing (npm run icons): " + missing.slice(0, 5).join(", ") + (missing.length > 5 ? " …" : ""));

// every string a translation file must have: tr("…")/fmt("…") calls, data-tr, and the toolbar's labels
export function strings(dir) {
  const files = walk(dir).filter((f) => /\/(scripts|lib)\/[^/]+\.js$|\.html$/.test(posix(f)) && !f.endsWith("pcm-worklet.js"));
  const keys = new Set();
  for (const f of files) {
    const s = readFileSync(f, "utf8");
    for (const m of s.matchAll(/\b(?:tr|fmt)\("((?:[^"\\]|\\.)+)"/g)) keys.add(JSON.parse('"' + m[1] + '"'));
    for (const m of s.matchAll(/data-tr(?:-title)?="([^"]+)"/g)) keys.add(m[1]);
    for (const m of s.matchAll(/^\s+\["\w+", "([^"]+)", "([^"]+)"\],?$/gm)) { keys.add(m[1]); keys.add(m[2]); }
    for (const m of s.matchAll(/\b(?:labels|map|LANGS) = \{([^}]+)\}/g)) {
      for (const v of m[1].matchAll(/:\s*"([^"]+)"/g)) keys.add(v[1]);
    }
    for (const m of s.matchAll(/text: "((?:[^"\\]|\\.)+)", url/g)) keys.add(m[1]);
  }
  return [...keys].sort();
}
const keys = strings(out);
for (const lang of JSON.parse(readFileSync(join(out, "translations", "langs.json"), "utf8"))) {
  const t = JSON.parse(readFileSync(join(out, "translations", lang + ".json"), "utf8"));
  const gaps = keys.filter((k) => !t[k]);
  if (gaps.length) throw new Error(`${lang}: ${gaps.length} strings not translated: ${gaps.slice(0, 5).map((g) => JSON.stringify(g)).join(", ")}`);
}

const manifest = walk(out).filter((f) => !f.endsWith("files.sha256")).map((f) =>
  `${createHash("sha256").update(readFileSync(f)).digest("hex")}  ${posix(relative(out, f))}`);
writeFileSync(join(out, "files.sha256"), manifest.join("\n") + "\n");
console.log(`${config.name} ${config.version} (${config.guid}) in ${out}: ${manifest.length} files, ${keys.length} strings`);
