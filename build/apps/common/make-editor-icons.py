#!/usr/bin/env python3
"""Writes editor-icons.js: the document editors' own toolbar icons (web-apps, Euro-Office / ONLYOFFICE, AGPL-3.0 like
the rest of the editors this app ships with), keyed by the names ribbon.js uses, drawn in currentColor so they follow
the theme. Run with the path to a web-apps checkout:  build/apps/common/make-editor-icons.py <web-apps>"""
import json, re, sys
from pathlib import Path

root = Path(sys.argv[1]) / "apps"
small = root / "common/main/resources/img/toolbar/2.5x"
big = small / "big"
de = root / "documenteditor/main/resources/img/toolbar/2.5x"
# ribbon name -> (small file, big file or None)
MAP = {
    "open": ("btn-open", None), "save": ("btn-save", None), "print": ("btn-print", None), "export": ("btn-download", None),
    "undo": ("btn-undo", None), "redo": ("btn-redo", None), "remove": ("btn-close", None), "duplicate": ("btn-copy", None),
    "indent": ("btn-incoffset", None), "outdent": ("btn-decoffset", None), "link": ("btn-inserthyperlink", "btn-big-inserthyperlink"),
    "table": ("btn-menu-table", "btn-inserttable"), "zoomin": ("btn-zoomup", None), "zoomout": ("btn-zoomdown", None),
    "fit": ("btn-ic-zoomtopage", None), "pointer": ("btn-select-all", "btn-select"), "alignleft": ("btn-shape-align-left", None),
    "aligncenter": ("btn-shape-align-center", None), "alignright": ("btn-shape-align-right", None), "aligntop": ("btn-shape-align-top", None),
    "alignmiddle": ("btn-shape-align-middle", None), "alignbottom": ("btn-shape-align-bottom", None),
    "distribute": ("btn-shape-distribute-hor", None), "distributev": ("btn-shape-distribute-vert", None),
    "comment": ("btn-add-comment", "btn-big-add-comment"), "comments": ("btn-menu-comments", "btn-big-menu-comments"),
    "group": ("btn-shape-group", "btn-img-group"), "ungroup": ("btn-shape-ungroup", None), "front": ("btn-arrange-front", "btn-img-frwd"),
    "back": ("btn-arrange-back", "btn-img-bkwd"), "template": ("btn-create-new", None), "theme": ("btn-colorschemas", "btn-big-colorschemas"),
    "ai": ("btn-general-ai", None), "calendar": ("btn-date", "btn-day"), "check": ("btn-ic-docspell", None),
    "page": ("btn-page-portrait", "btn-pagesize"), "pageframe": ("btn-page-landscape", "btn-pageorient"), "list": ("btn-numbering", None),
    "report": ("btn-menu-chart", "btn-insertchart"), "outline": ("btn-menu-shape", "btn-insertshape"), "search": ("btn-menu-search", None),
    "settings": ("btn-settings", "btn-properties"), "text": ("btn-text", "btn-big-text"), "image": ("btn-menu-image", "btn-insertimage"),
    "lock": ("btn-lock", None), "rename": ("btn-rename", None), "update": ("btn-update", "btn-update"),
}

def body(path):
    s = path.read_text(encoding="utf-8")
    m = re.search(r"<svg([^>]*)>(.*)</svg>", s, re.S)
    vbm = re.search(r'viewBox="([^"]+)"', m.group(1))
    w = re.search(r'width="(\d+)"', m.group(1)); h = re.search(r'height="(\d+)"', m.group(1))
    vb = vbm.group(1) if vbm else f"0 0 {w.group(1) if w else 20} {h.group(1) if h else 20}"
    inner = re.sub(r'fill="#(000|000000|fff|ffffff)"', 'fill="currentColor"', m.group(2), flags=re.I)
    inner = re.sub(r'stroke="#(000|000000)"', 'stroke="currentColor"', inner, flags=re.I)
    return {"viewBox": vb, "body": re.sub(r"\s+", " ", inner).strip()}

out = {}
for name, (sm, bg) in MAP.items():
    entry = {}
    for kind, fname, folders in (("small", sm, [small, de]), ("big", bg, [big])):
        if not fname:
            continue
        for f in folders:
            p = f / f"{fname}.svg"
            if p.exists():
                entry[kind] = body(p)
                break
    if entry:
        out[name] = entry
js = ("// Generated by make-editor-icons.py from web-apps (Euro-Office / ONLYOFFICE editors, AGPL-3.0): the document editors'\n"
      "// own toolbar icons, small (20) and big, in currentColor. Do not edit by hand; run the script again.\n"
      "export const EDITOR_ICONS = " + json.dumps(out, indent=0, sort_keys=True) + ";\n")
Path(__file__).with_name("editor-icons.js").write_text(js, encoding="utf-8")
print(f"{len(out)} icons")
